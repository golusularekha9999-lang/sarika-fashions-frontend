export const getProductById = (id) =>
  products.find((p) => String(p.id) === String(id))

// ============================================================
// GET RELATED PRODUCTS
// ============================================================

export const getRelatedProducts = (product, count = 4) =>
  products
    .filter(
      (p) =>
        p.category === product.category &&
        p.id !== product.id
    )
    .slice(0, count)